// Build motion/films/silence400/advent.js from the first film's 11 advent.html (backlit Gothic stained glass: the promises' panes
// wake one by one at dawn, the star ignites, the nativity lancet lights, the camera pushes into the manger, then tilts down the
// shafts to the coloured light on the floor) — picture only: its stone labels and screen text are left out.
//   node motion/films/silence400/make-advent.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const R = 'C:/Project/one-scroll-bible/motion/', src = readFileSync(R + 'pilot/advent.html', 'utf8');
const js = src.slice(src.indexOf('<script>\n/* 11') + 9, src.lastIndexOf('Pilot.run('));
const a = js.indexOf('  // labels cut in the stone'), b = js.indexOf('  ctx.restore();\n\n  // screen-space type'), c = js.indexOf('\n}\n', b);
if (a < 0 || b < 0 || c < 0) throw new Error('markers');
const body = js.slice(0, a) + js.slice(b, js.indexOf('  // screen-space type', b)) + '}\n' + js.slice(c + 3);
const init = src.slice(src.indexOf('init: async () => {') + 'init: async () => {'.length, src.lastIndexOf('},\n  draw });'));
const out = `/* GENERATED by make-advent.mjs from motion/pilot/advent.html (the first film's stained-glass nativity) — picture only, no words.
   Advent.init() once; Advent.draw(ctx, localT) on the original scene's clock (0–36 s: panes wake 3.2–11.6, the star 14.3,
   the nativity 15.0, push into the manger 13.4–21.6, tilt down to the floor 21.6–25.4). Do not edit by hand: rerun the generator. */
window.Advent = (function () {
${body.replace(/^/gm, '  ')}
  return { init: async () => {${init}}, draw };
})();
`;
writeFileSync(R + 'films/silence400/advent.js', out);
console.log('advent.js', out.length);
