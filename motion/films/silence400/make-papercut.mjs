// Build motion/films/silence400/papercut.js from the first film's 10 silence.html (the paper-cut lightbox), without its words:
// the scene's own drawing code, wrapped so the new film can play it at any local time (Papercut.draw(ctx, localT)).
import { readFileSync, writeFileSync } from 'node:fs';
const R = 'C:/Project/one-scroll-bible/motion/';
const src = readFileSync(R + 'pilot/silence.html', 'utf8');
const js = src.slice(src.indexOf('<script>\n/* 10') + 9, src.lastIndexOf('Pilot.run('));
const head = js.slice(0, js.indexOf('// ---------- frame ----------'));
const extras = js.slice(js.indexOf('function skyExtras'));
const drawFn = js.slice(js.indexOf('function years(t)'), js.indexOf('function skyExtras'));
// keep the picture, drop the words (everything from "// words" to the fade at the end)
const pic = drawFn.slice(0, drawFn.indexOf('  // words')) + '}\n';
const init = src.slice(src.indexOf('init: async () => {') + 'init: async () => {'.length, src.lastIndexOf('},\n  draw });'));
const out = `/* GENERATED by make-papercut.mjs from motion/pilot/silence.html (the first film's "400년 침묵" paper-cut lightbox) — picture only,
   no words. Papercut.init() once; Papercut.draw(ctx, localT) with localT on the original scene's clock (0–34 s:
   lamp on 0.6 s, the years and seasons 8–24.4 s, the new light 24.8 s). Do not edit by hand: rerun the generator. */
window.Papercut = (function () {
${head.replace(/^/gm, '  ')}
${pic.replace(/^/gm, '  ')}
${extras.replace(/^/gm, '  ')}
  return { init: async () => {${init}}, draw };
})();
`;
writeFileSync(R + 'films/silence400/papercut.js', out);
console.log('papercut.js', out.length, 'bytes');
